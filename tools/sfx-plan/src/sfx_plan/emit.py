"""Emit compositions/sfx.html + stage assets into the video folder.

HyperFrames sub-compositions must (a) live inside the video folder for asset
discovery, (b) wrap content in a `<template>` + composition-root `<div>`,
(c) register the timeline on `window.__timelines`, and (d) tag every timed
media element with `class="clip"` and a stable `id`.
"""
from __future__ import annotations

import hashlib
import os
import re
from datetime import datetime, timezone
from pathlib import Path

from sfx_plan.plan import Cue


SFX_LAYER_ID = "sfx-layer"
SFX_MOUNT_TRACK_INDEX = 19


def _slug(text: str) -> str:
    """ASCII-safe lowercase slug for use in HTML ids."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "x"


def stage_assets(
    cues: list[Cue],
    *,
    sound_effects_root: Path,
    video_dir: Path,
) -> dict[str, str]:
    """Stage each unique cue source as a relative symlink under `video_dir/assets/sfx/`.

    Returns a map from original `cue.src` (catalog-relative) to staged path
    (video-folder-relative). Files with name collisions get an 8-char hash prefix.
    Links are relative so the video folder stays portable across clones as long
    as `sound-effects/` lives at the repo root.
    """
    sfx_dir = video_dir / "assets" / "sfx"
    sfx_dir.mkdir(parents=True, exist_ok=True)
    staged: dict[str, str] = {}
    for cue in cues:
        if cue.src in staged:
            continue
        source = (sound_effects_root / cue.src).resolve()
        basename = source.name
        dest = sfx_dir / basename
        if dest.exists() and dest.stat().st_size != source.stat().st_size:
            h = hashlib.sha256(cue.src.encode("utf-8")).hexdigest()[:8]
            dest = sfx_dir / f"{h}-{basename}"
        if dest.is_symlink() and not dest.exists():
            dest.unlink()
        if not dest.exists():
            rel_target = os.path.relpath(source, start=dest.parent)
            dest.symlink_to(rel_target)
        staged[cue.src] = dest.relative_to(video_dir).as_posix()
    return staged


def _audio_tag(*, cue: Cue, index: int, staged_rel: str, video_to_sfx_relpath: str) -> str:
    label = cue.anchor if cue.anchor is not None else f"scene-ms-{cue.at_scene_ms}"
    audio_id = f"sfx-{index:03d}-{cue.cue}-{_slug(label)}"
    if cue.anchor is not None:
        ref = f'anchor="{cue.anchor}" idx={cue.anchor_index}'
    else:
        ref = f'at-scene-ms={cue.at_scene_ms}'
    comment = (
        f'        <!-- from {cue.source}  {ref}  '
        f'cue={cue.cue} -->'
    )
    pan = "" if cue.pan == 0.0 else f'\n          data-pan="{cue.pan}"'
    return (
        f'{comment}\n'
        f'        <audio\n'
        f'          id="{audio_id}"\n'
        f'          class="clip"\n'
        f'          data-start="{cue.data_start}"\n'
        f'          data-duration="{cue.duration_s}"\n'
        f'          data-volume="{cue.volume}"{pan}\n'
        f'          data-track-index="{cue.track_index}"\n'
        f'          src="{video_to_sfx_relpath}/{Path(staged_rel).name}"\n'
        f'        ></audio>'
    )


def render_sfx_html(
    *,
    cues: list[Cue],
    sfx_html_path: Path,
    video_dir: Path,
    staged: dict[str, str],
    catalog_sha: str,
    total_duration_s: float,
) -> str:
    """Produce the full text of compositions/sfx.html as a HyperFrames sub-composition."""
    ordered = sorted(cues, key=lambda c: c.data_start)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    # Compute relative path from sfx.html's parent to assets/sfx (typically "../assets/sfx").
    sfx_assets_dir = (video_dir / "assets" / "sfx").resolve()
    sfx_html_parent = sfx_html_path.parent.resolve()
    import os
    rel_to_sfx = os.path.relpath(sfx_assets_dir, start=sfx_html_parent).replace(os.sep, "/")

    audio_blocks = "\n".join(
        _audio_tag(
            cue=c,
            index=i + 1,
            staged_rel=staged[c.src],
            video_to_sfx_relpath=rel_to_sfx,
        )
        for i, c in enumerate(ordered)
    )

    return (
        f"<!--\n"
        f"  GENERATED by tools/sfx-plan — do not edit by hand.\n"
        f"  Source: sfx-plan v1, run at {ts}\n"
        f"  Cues: {len(ordered)}   Duration: {total_duration_s:.1f}s   "
        f"Catalog: sfx-catalog.yml@{catalog_sha[:12]}\n"
        f"-->\n"
        f'<!doctype html>\n'
        f'<html lang="en">\n'
        f'  <head>\n'
        f'    <meta charset="UTF-8" />\n'
        f'    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>\n'
        f'  </head>\n'
        f'  <body>\n'
        f'    <template id="{SFX_LAYER_ID}-template">\n'
        f'      <div\n'
        f'        data-composition-id="{SFX_LAYER_ID}"\n'
        f'        data-width="1920"\n'
        f'        data-height="1080"\n'
        f'      >\n'
        f'{audio_blocks}\n'
        f'        <script>\n'
        f'          (() => {{\n'
        f'            window.__timelines = window.__timelines || {{}};\n'
        f'            window.__timelines["{SFX_LAYER_ID}"] = gsap.timeline({{ paused: true }});\n'
        f'          }})();\n'
        f'        </script>\n'
        f'      </div>\n'
        f'    </template>\n'
        f'  </body>\n'
        f'</html>\n'
    )


def _mount_block(total_duration_s: float) -> str:
    return (
        '      <!-- sfx-layer: generated by tools/sfx-plan, do not edit -->\n'
        '      <div\n'
        f'        id="{SFX_LAYER_ID}"\n'
        f'        data-composition-id="{SFX_LAYER_ID}"\n'
        f'        data-composition-src="compositions/sfx.html"\n'
        f'        data-start="0"\n'
        f'        data-duration="{total_duration_s}"\n'
        f'        data-track-index="{SFX_MOUNT_TRACK_INDEX}"\n'
        '      ></div>\n'
    )


def ensure_mount(index_html_path: Path, *, total_duration_s: float) -> bool:
    """Insert the sfx-layer mount into index.html if absent. Returns True if changed."""
    text = index_html_path.read_text(encoding="utf-8")
    if 'data-composition-src="compositions/sfx.html"' in text:
        return False
    mount = _mount_block(total_duration_s)
    if "</body>" in text:
        new_text = text.replace("</body>", mount + "</body>", 1)
    else:
        new_text = text + "\n" + mount
    index_html_path.write_text(new_text, encoding="utf-8")
    return True
